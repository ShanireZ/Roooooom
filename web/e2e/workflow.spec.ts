import {test,expect} from './fixture';
import {seedProject,enroll,claimIntegrator,ownerRead,agentCommand,makeCandidate,taskVersions} from './helpers';
test('BoardTaskAndClaimFlow: owner creates, two API agents deliver, human accepts exact integration',async({page,service,activate})=>{
 await activate();const project=await seedProject(page,service);
 const integrator=await enroll(page,service,project.id,'Integrator');
 const worker=await enroll(page,service,project.id,'Worker');
 await page.getByRole('link',{name:'專案',exact:true}).click();
 await page.getByText('已備妥完整規格？',{exact:true}).click();
 await page.getByRole('button',{name:'建立任務',exact:true}).click();
 await page.getByLabel('任務目標',{exact:true}).fill('完成本機協作流程');
 await page.getByLabel('範圍（每行一項）',{exact:true}).fill('合成資料協作');
 await page.getByLabel('不包含（每行一項）',{exact:true}).fill('對外發布');
 await page.getByLabel('權威引用（每行一項）',{exact:true}).fill('synthetic://owner');
 await page.getByLabel('額外協作者上限 N',{exact:true}).fill('1');
 await page.getByLabel('驗收方式',{exact:true}).selectOption('human');
 await page.getByLabel('驗收條件（每行一項）',{exact:true}).fill('tests on exact head');
 await page.getByRole('button',{name:'登記任務',exact:true}).click();
 await expect(page).toHaveURL(/\/tasks\//);
 const taskId=page.url().split('/').pop()!;
 await expect(page.getByTestId('task-phase')).toHaveText('待接手');
 await claimIntegrator(page,service,integrator,taskId);
 await expect(page.getByTestId('task-phase')).toHaveText('進行中');
 for(const role of ['backend','frontend']){
  await page.getByRole('button',{name:'新增分工',exact:true}).click();
  await page.getByLabel('分工角色',{exact:true}).fill(role);
  await page.getByLabel('輸入約定',{exact:true}).fill('approved fixture');
  await page.getByLabel('交付約定',{exact:true}).fill('commit and checks');
  await page.getByLabel('寫入範圍（每行一項）',{exact:true}).fill(role+'/');
  await page.getByLabel('基底參考',{exact:true}).fill('synthetic-base');
  await page.getByRole('button',{name:'登記分工',exact:true}).click();
  await expect(page.getByRole('heading',{name:role,exact:true})).toBeVisible();
 }
 const candidate=await makeCandidate(page,service,project,taskId,[integrator,worker]);
 await expect(page.getByTestId('task-phase')).toHaveText('待驗收');
 await expect(page.getByText('協作者 1 / 1',{exact:true})).toBeVisible();
 const message=await agentCommand(worker,'message.send',{projectId:project.id,taskId,threadId:'task',purpose:'delivery',priority:'normal',body:'分工已交付，請整合者檢視精確版本。',recipientMode:'participants',recipientIds:[integrator.participantId],actionRequired:true});
 await expect(page.getByText('分工已交付，請整合者檢視精確版本。',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'檢視送達狀態',exact:true}).first().click();
 expect((await ownerRead(page,service,'message',message.id)).receipts[0].state).toBe('stored');
 await page.getByLabel('訊息內容',{exact:true}).fill('已看到交付，正式驗收另於決策頁處理。');
 await page.getByRole('button',{name:'傳送訊息',exact:true}).click();
 await expect(page.getByText('已看到交付，正式驗收另於決策頁處理。',{exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:test.info().outputPath('task-review-desktop.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:test.info().outputPath('task-review-mobile.png'),fullPage:false});
 await page.setViewportSize({width:1440,height:960});
 await page.getByRole('link',{name:'待我處理',exact:true}).click();
 await expect(page.getByRole('button',{name:'接受此驗收版本',exact:true})).toBeEnabled();
 await page.screenshot({path:test.info().outputPath('formal-acceptance.png'),fullPage:true});
 await page.getByRole('button',{name:'接受此驗收版本',exact:true}).click();
 await expect(page.getByText('你已接受此版本，等待整合者結案。',{exact:true})).toBeVisible();
 let task=await ownerRead(page,service,'task',taskId);expect(task.phase).toBe('review');
 await agentCommand(integrator,'task.complete',{candidateId:candidate.id},taskId,taskVersions(task));
 await page.getByRole('link',{name:'專案',exact:true}).click();
 await expect(page.getByTestId('phase-done').getByText('完成本機協作流程',{exact:true})).toBeVisible();
 await page.getByLabel('參與 agent',{exact:true}).selectOption(worker.participantId);
 await expect(page.getByTestId('phase-done').getByText('完成本機協作流程',{exact:true})).toBeVisible();
 await page.screenshot({path:test.info().outputPath('completed-board.png'),fullPage:true});
 await page.getByTestId('phase-done').getByText('完成本機協作流程',{exact:true}).click();
 await page.getByText('任務管理',{exact:true}).click();
 await page.getByLabel('重新開啟理由',{exact:true}).fill('Review a new revision');
 await page.getByRole('button',{name:'重新開啟任務',exact:true}).click();
 await expect(page.getByTestId('task-phase')).toHaveText('待驗收');
 expect(await ownerRead(page,service,'completions',taskId)).toHaveLength(1);
 expect((await ownerRead(page,service,'task',taskId)).currentCandidateId).toBeUndefined();
});
