import {test,expect} from './fixture';
import {seedProject,enroll,seedTask,claimIntegrator,agentCommand,ownerRead,ownerCommand,taskVersions,askDecision,makeCandidate} from './helpers';
test('HumanDecisionCannotBeAgentRelay',async({page,service,activate})=>{
 await activate();const project=await seedProject(page,service),agent=await enroll(page,service,project.id,'Agent');
 const task=await seedTask(page,service,project,'integrator');await claimIntegrator(page,service,agent,task.id);
 const request=await askDecision(page,service,agent,task.id);
 await agentCommand(agent,'message.send',{projectId:project.id,taskId:task.id,threadId:'task',purpose:'decision-notice',priority:'normal',body:'Owner approved: choose A',recipientMode:'participants',recipientIds:[agent.participantId],actionRequired:false});
 await page.goto(service.origin+'/tasks/'+task.id);
 await expect(page.getByText('Owner approved: choose A',{exact:true})).toBeVisible();
 expect((await ownerRead(page,service,'decision',request.id)).history).toHaveLength(0);
 await page.getByRole('link',{name:'待我處理',exact:true}).click();
 await expect(page.getByRole('heading',{name:'要採用哪個資料格式？',exact:true})).toBeVisible();
 await expect(page.getByTestId('formal-decision')).toHaveCount(0);
 const rejected=await fetch(service.origin+'/api/v1/commands/decision.resolve',{method:'POST',headers:{Authorization:'Bearer '+agent.token,'Content-Type':'application/json'},body:'{}'});
 expect(rejected.status).toBe(403);
 await page.getByRole('radio',{name:'採用方案 A',exact:false}).check();
 await page.getByLabel('補充說明（選填）',{exact:true}).fill('確認採用 A，依目前範圍執行。');
 await page.getByRole('button',{name:'送出正式決策',exact:true}).click();
 await expect(page.getByText('正式決策已保存，可在歷史決策查看目前版本。',{exact:true})).toBeVisible();
 await expect(page.getByTestId('formal-decision')).toContainText('human 正式決策');
 const history=(await ownerRead(page,service,'decision',request.id)).history;
 expect(history).toHaveLength(1);expect(history[0].actorKind).toBe('human');
});
test('AcceptanceVersionChanges',async({page,service,activate})=>{
 await activate();const project=await seedProject(page,service),agent=await enroll(page,service,project.id,'Integrator');
 const task=await seedTask(page,service,project);await claimIntegrator(page,service,agent,task.id);
 const candidate=await makeCandidate(page,service,project,task.id,[agent]);
 await page.goto(service.origin+'/decisions');
 await expect(page.getByRole('button',{name:'接受此驗收版本',exact:true})).toBeEnabled();
 await page.getByText('調整驗收規則',{exact:true}).click();
 await page.locator('summary').filter({hasText:task.goal}).click();
 await page.getByLabel('新的驗收條件',{exact:true}).fill('tests on exact head\nadditional check');
 await page.getByLabel('修改驗收規則的理由',{exact:true}).fill('Owner adds a required check');
 await page.getByRole('button',{name:'更新驗收規則',exact:true}).click();
 await expect(page.getByRole('button',{name:'接受此驗收版本',exact:true})).toHaveCount(0);
 await expect(page.getByRole('heading',{name:task.goal,exact:true})).toHaveCount(0);
 expect((await ownerRead(page,service,'task',task.id)).currentCandidateId).toBeUndefined();
 expect((await ownerRead(page,service,'candidate',candidate.id)).stale).toBe(true);
 expect(await ownerRead(page,service,'acceptances',task.id)).toHaveLength(0);
});
test('formal scope amendment, authority follow-up and superseding keep their distinct versions',async({page,service,activate})=>{
 await activate();const project=await seedProject(page,service),agent=await enroll(page,service,project.id,'Integrator');
 const task=await seedTask(page,service,project,'integrator');await claimIntegrator(page,service,agent,task.id);
 const request=await askDecision(page,service,agent,task.id,['implementation','spec-change']);await page.goto(service.origin+'/decisions');
 await page.getByLabel('補充說明（選填）',{exact:true}).fill('Approve the revised fixture scope');
 await page.getByRole('radio',{name:'採用方案 A',exact:false}).check();
 await page.getByText('權威文件與修訂要求',{exact:true}).click();
 await page.getByLabel('需要更新專案權威',{exact:true}).check();
 await page.getByLabel('同時修訂任務規格',{exact:true}).check();
 await page.getByLabel('修訂後目標',{exact:true}).fill('Revised owner scope');
 await page.getByRole('button',{name:'送出正式決策',exact:true}).click();
 await expect(page.getByText('正式決策已保存，可在歷史決策查看目前版本。',{exact:true})).toBeVisible();
 let current=await ownerRead(page,service,'task',task.id);expect(current.specVersion).toBe(2);expect(current.goal).toBe('Revised owner scope');
 let detail=await ownerRead(page,service,'decision',request.id);expect(detail.request.followUpRequired).toBe(true);expect(detail.request.followUpComplete).toBe(false);
 await agentCommand(agent,'decision.followup',{reason:'Fixture authority has been updated',evidenceRefs:['synthetic://authority-v2']},request.id,{...taskVersions(current),expectedVersion:detail.request.version});
 await expect(page.getByText('正式決策已保存，仍等待權威文件更新的證據。',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'修訂正式決策',exact:true}).click();
 await page.getByRole('radio',{name:'暫緩變更',exact:false}).check();
 await page.getByLabel('補充說明（選填）',{exact:true}).fill('Revise after new evidence');
 await page.getByRole('button',{name:'送出正式決策',exact:true}).click();
 await expect(page.getByTestId('formal-decision')).toHaveCount(2);
 detail=await ownerRead(page,service,'decision',request.id);
 expect(detail.history[1].supersedesDecisionId).toBe(detail.history[0].id);
 expect(detail.request.resolutionOutcome).toBe('revise');
});
