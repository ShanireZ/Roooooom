import {test,expect} from '../fixture';
import {agentCommand,claimIntegrator,enroll,makeCandidate,ownerRead,seedProject,taskVersions} from '../helpers';
import {m} from '../i18n';

test.use({locale:'en-US'});

test('BoardTaskAndClaimFlow: owner creates, two API agents deliver, human accepts exact integration',async({page,service,activate})=>{
 await page.setViewportSize({width:1440,height:960});
 await activate();const project=await seedProject(page,service);
 const integrator=await enroll(page,service,project.id,'Integrator'),worker=await enroll(page,service,project.id,'Worker');
 const goal='Finish the local collaboration flow';
 await page.goto(service.origin+'/rooms/'+project.id);
 await page.getByRole('button',{name:m('composer.fullSpec')}).click();
 const editor=page.getByRole('dialog',{name:m('create.title')});
 await editor.getByLabel(m('create.goal'),{exact:true}).fill(goal);
 await editor.getByLabel(m('create.scope'),{exact:true}).fill('synthetic collaboration');
 await editor.getByLabel(m('create.nonScope'),{exact:true}).fill('publication');
 await editor.getByLabel(m('create.authority'),{exact:true}).fill('synthetic://owner');
 await editor.getByLabel(m('composer.limit'),{exact:true}).fill('1');
 await editor.getByLabel(m('create.acceptanceMode'),{exact:true}).selectOption('human');
 await editor.getByLabel(m('create.conditions'),{exact:true}).fill('tests on exact head');
 await editor.getByRole('button',{name:m('create.submit'),exact:true}).click();
 await expect(page).toHaveURL(/\/tasks\//);
 const taskId=new URL(page.url()).pathname.split('/')[4];
 const d=page.getByRole('dialog',{name:goal});
 await expect(d).toContainText(m('phase.ready'));
 await claimIntegrator(page,service,integrator,taskId);
 await expect(d).toContainText(m('phase.active'));
 await d.getByRole('link',{name:m('task.tab.work'),exact:true}).click();
 for(const role of ['backend','frontend']){
  await d.getByRole('button',{name:m('work.add'),exact:true}).click();
  await d.getByLabel(m('work.role'),{exact:true}).fill(role);
  await d.getByLabel(m('work.input'),{exact:true}).fill('approved fixture');
  await d.getByLabel(m('work.output'),{exact:true}).fill('commit and checks');
  await d.getByLabel(m('work.scope'),{exact:true}).fill(role+'/');
  await d.getByLabel(m('work.base'),{exact:true}).fill('synthetic-base');
  await d.getByRole('button',{name:m('work.submit'),exact:true}).click();
  await expect(d.getByText(role,{exact:true}).first()).toBeVisible();
 }
 const candidate=await makeCandidate(page,service,project,taskId,[integrator,worker]);
 await d.getByRole('link',{name:m('task.tab.overview'),exact:true}).click();
 await expect(d).toContainText(m('phase.review'));
 await expect(d).toContainText(m('task.collaborators',{count:1,limit:1}));
 const body='The assignment is delivered; please review the exact version.';
 const message=await agentCommand(worker,'message.send',{projectId:project.id,taskId,threadId:'task',purpose:'delivery',priority:'normal',body,recipientMode:'participants',recipientIds:[integrator.participantId],actionRequired:true});
 await d.getByRole('link',{name:m('task.tab.discussion'),exact:true}).click();
 const entry=d.getByRole('listitem').filter({hasText:body});
 await expect(entry).toBeVisible();
 await entry.getByText(m('discussion.receipts')).click();
 expect((await ownerRead(page,service,'message',message.id)).receipts[0].state).toBe('stored');
 await d.getByLabel(m('composer.sayLabel')).fill('Seen the delivery; formal acceptance happens separately.');
 await d.getByRole('button',{name:m('composer.saySubmit')}).click();
 await expect(d.getByRole('list',{name:m('task.tab.discussion')})).toContainText('Seen the delivery');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.setViewportSize({width:1440,height:960});
 await page.getByRole('button',{name:new RegExp(m('shell.needsYou'))}).click();
 await page.locator('#needs-you-panel').getByRole('link',{name:new RegExp(goal)}).click();
 await expect(page).toHaveURL(new RegExp('/acceptance/'+taskId));
 await page.getByRole('button',{name:m('acceptance.accept')}).click();
 await expect(page.getByText(m('acceptance.accepted'))).toBeVisible();
 const task=await ownerRead(page,service,'task',taskId);expect(task.phase).toBe('review');
 await agentCommand(integrator,'task.complete',{candidateId:candidate.id},taskId,taskVersions(task));
 await page.goto(service.origin+'/rooms/'+project.id+'/archive');
 await page.getByRole('dialog').getByRole('link',{name:goal}).click();
 await page.getByRole('dialog',{name:goal}).getByRole('link',{name:m('task.tab.manage'),exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:m('manage.reopen'),exact:true}).click();
 await page.getByRole('dialog').getByLabel(m('manage.reopenReason')).fill('Review a new revision');
 await page.getByRole('dialog').getByRole('button',{name:m('manage.confirmReopen'),exact:true}).click();
 await expect.poll(async()=>(await ownerRead(page,service,'task',taskId)).phase).toBe('review');
 expect(await ownerRead(page,service,'completions',taskId)).toHaveLength(1);
 expect((await ownerRead(page,service,'task',taskId)).currentCandidateId).toBeUndefined();
});
