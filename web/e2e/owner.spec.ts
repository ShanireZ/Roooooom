 await page.getByLabel('Repository 1 引用',{exact:true}).fill('synthetic://fixture');
 await page.getByRole('button',{name:'登記專案',exact:true}).click();
 await expect(page.getByText('專案已登記。',{exact:true})).toBeVisible();
 const grantResponse=page.waitForResponse(r=>r.url().endsWith('/commands/enrollment.enable'));
 await page.getByText('接入與成員管理',{exact:true}).click();
 await page.getByRole('button',{name:'開放本機 agent 登記',exact:true}).click();
 const grant=(await (await grantResponse).json()).result;
 const config=JSON.parse(await readFile(grant.enrollmentPath,'utf8'));
 const identity=await (await page.request.get(service.origin+'/identity')).json();
 const response=await fetch(service.origin+'/api/v1/enroll',{method:'POST',headers:{Authorization:'Bearer '+config.capability,'Content-Type':'application/json'},body:JSON.stringify({serviceId:identity.serviceId,datasetGeneration:identity.datasetGeneration,clientRequestId:crypto.randomUUID(),name:'Settings agent'})});
 expect(response.ok).toBe(true);const original=(await response.json()).result;
 await expect(page.getByText('Settings agent',{exact:true})).toBeVisible();
 const recoveryResponse=page.waitForResponse(r=>r.url().endsWith('/commands/participant.recover'));
 await page.getByRole('button',{name:'核發恢復檔',exact:true}).click();
 const recovery=(await (await recoveryResponse).json()).result;
 const credentials=JSON.parse(await readFile(recovery.credentialPath,'utf8'));
 expect(credentials.participantId).toBe(original.participantId);expect(credentials.sessionId).not.toBe(original.sessionId);
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'撤銷接入',exact:true}).click();
 await expect(page.getByText('已撤銷接入。',{exact:true})).toBeVisible();
